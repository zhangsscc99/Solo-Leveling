// 按章取池：数据漂移（未知章节号/池缺字段）回落 GENERIC，不回退第 1 章。
function poolFor(chapterIndex) {
  const pool = POOLS[Math.trunc(Number(chapterIndex) || 0)];
  if (!pool) return GENERIC;
  // 逐项合并兜底：某章只写了部分动作时，缺的项用通用文案补齐。
  const merged = {};
  for (const key of Object.keys(GENERIC)) merged[key] = pool[key] || GENERIC[key];
  return merged;
}

// 确定性轮转：外部传入单调计数（如已观察次数）作 n，连续两次取不同条。
function pick(list, n) {
  const arr = Array.isArray(list) && list.length ? list : GENERIC.observe;
  return arr[Math.abs(Math.trunc(Number(n) || 0)) % arr.length];
}

