const BY_NAME = new Map(ENTITIES.map((e) => [e.name, e]));

// 玩家原文里点名的实体 → 规范名；没点名 → null。
function extractEntity(input) {
  try {
    const text = typeof input === "string" ? input : "";
    if (!text) return null;
    for (const e of ENTITIES) {
      if (e.match.test(text)) return e.name;
    }
    return null;
  } catch {
    return null;
  }
}

// 场景正文（blob）里真实在场的实体名，按 ENTITIES 固定顺序返回。
function entitiesIn(blob) {
  try {
    const text = typeof blob === "string" ? blob : "";
    return ENTITIES.filter((e) => e.match.test(text)).map((e) => e.name);
  } catch {
    return [];
  }
}

// 实体专属细节句：n 按 (save_id, entity) 外部计数传入，确定性轮换。
// 未知实体名回落 null——调用方自行兜底，本函数不捏造。
function detail(entity, n) {
  try {
    const e = BY_NAME.get(entity);
    if (!e) return null;
    const i = Math.abs(Math.trunc(Number(n) || 0)) % e.lines.length;
    return e.lines[i];
  } catch {
    return null;
  }
}

module.exports = { ENTITIES, extractEntity, entitiesIn, detail };
